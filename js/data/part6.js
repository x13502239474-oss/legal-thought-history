<h4>三、法治与人治</h4>
<p>法治与人治的对立，是亚里士多德命题的现代回响。人治意味着权力依照统治者个人的意志、情绪与判断运作，其根本缺陷在于不可预期且容易偏私：即便统治者当时贤明，也无法保证继承者同样贤明，更无法消除权力对人性的腐蚀。法治则以一般规则取代个人意志，使公民能够预见行为的后果，并让权力受到制度性约束。然而，把法治理解为『机械地套用规则』是一种误解。亚里士多德早已指出，法律的一般规定在个案中可能导致不公，因此需要<em>衡平</em>来矫正；现代法治同样承认法官在疑难案件中的自由裁量。问题在于如何既允许必要的裁量，又不让裁量沦为恣意——这正引出司法独立与司法问责的平衡问题。</p>
<h4>四、宪政与权力制约：宪法至上与违宪审查</h4>
<p>法治要真正约束权力，仅靠『依法办事』不够，因为立法机关本身可能制定侵犯权利的法律。宪政的回应是把宪法确立为<strong>最高法</strong>，一切普通法律与权力行为都不得与之抵触。这一原则最早在美国宪法第六条获得明文表述，并通过一八〇三年马伯里诉麦迪逊案转化为可操作的制度：法院有权审查国会立法是否违宪，并拒绝适用违宪的法律。违宪审查此后发展出两种主要模式。其一是<em>分散式</em>，以美国为代表，由普通法院在审理具体案件时附带审查，任何法官都可作出违宪判断；其二是<em>集中式</em>，以德国为代表，设立专门的宪法法院集中审理宪法争议，普通法院须将合宪性问题移送之。两种模式各有拥护者：分散式贴近个案、由普通法官把关，集中式则更统一、更具政治分量。但违宪审查始终面临一个尖锐的正当性质疑：由非民选的法官否决民选议会通过的法律，是否违背了民主原则？这就是著名的『反多数难题』。支持者回答：宪法本身是更高层次的民主决定，法院守护的是长远的宪法价值与少数人权利；批评者则担忧司法积极主义侵蚀民主。这一争论至今未有定论，各国只是在不同平衡点上运行。</p>
<h4>五、司法独立及其边界</h4>
<p>司法独立是法治的支柱，通常包含机构与个人两个层面。<strong>法院独立</strong>要求法院系统作为一个整体在组织、财政与人事上相对独立于行政与立法机关，避免政府通过预算或人事控制影响审判。<strong>法官独立</strong>要求法官在个案中只服从法律与事实，不接受来自上级法官、行政机关或舆论的不当指令；为此需要任期保障、薪酬保障与不可任意调免等制度。中国宪法也确认人民法院依法独立行使审判权，不受行政机关、社会团体和个人的干涉。然而，独立若走向失控，也可能产生『司法帝国』的危险：法官若不受任何约束，其专横同样会侵害权利。因此现代法治强调<em>司法问责</em>——法官须公开裁判理由、接受上诉审与法律监督、对贪腐与枉法行为承担责任。独立与问责并非对立，而是同一枚硬币的两面：独立保障法官敢断，问责保证法官不乱断。</p>
<h4>六、法律确定性与溯及既往问题</h4>
<p>法律的确定性（法的安定性）要求规则清晰、稳定，公民能够据此规划自己的生活并预见国家行为的边界。它是法治可预期性的基础：如果法律朝令夕改、含义模糊，人们便无法安排行为，权力也就获得了随意解释的空间。与之紧密相连的是<em>不溯及既往</em>原则——法律原则上只适用于生效后的行为，不能用事后制定的法律惩罚先前的行为。这一原则在刑法上体现为『法无明文规定不为罪』，旨在防止国家以事后之法追究公民。第一章讨论的纽伦堡审判恰恰展示了这一原则的张力：若严格适用不溯及既往，纳粹暴行在当时『合法』将被放过；若事后立法追究，又触及溯及既往的禁忌。拉德布鲁赫公式正是对这一两难的回答：当法律与正义的矛盾达到『不可容忍』程度时，法律须向正义让步。这说明确定性与正义之间存在真实张力，法治的成熟恰在于审慎地处理这种张力，而非机械地倒向任何一端。</p>
<h4>七、基本权利与公民自由</h4>
